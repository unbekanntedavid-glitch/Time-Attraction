"""Generate the value macros, the generated tables and the claim-source table from the module archives.

usage: python3 make_values.py <modules_dir> <article_dir>
"""
import csv
import math
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from claimlib import MODULES, Store, evaluate, fmt, hu, plain, sel_str  # noqa: E402
from claims_spec import CLAIMS  # noqa: E402


def V(k):
    return "\\V{" + k + "}"


def tables():
    """Generated table bodies; each cell is a value macro, so every number has a claim row."""
    T = {}
    PS = ["P1", "P2", "P3"]
    T["params"] = "".join(f"{P} & {V('L'+P)} & {V('aY'+P)} & {V('alpha'+P)} & {V('aprime'+P)} & {V('Ginf'+P)}\\\\\n" for P in PS)
    T["results"] = "".join(f"{P} & {V('dy'+P)} & {V('da'+P)} & {V('dyRel'+P)} & {V('daRel'+P)}\\\\\n" for P in PS)
    T["scal"] = "".join(f"{P} & {V('dyLo'+P)} & {V('dy'+P)} & {V('dyHi'+P)} & {V('daLo'+P)} & {V('da'+P)} & {V('daHi'+P)}\\\\\n" for P in PS)
    T["bounds"] = "".join(
        f"{P} & {V('aLimLab'+P)} & {V('RLab'+P)} & {V('aLimBrenA'+P)}, {V('aLimBrenB'+P)}, {V('aLimBrenC'+P)} & "
        f"{V('RBrenMin'+P)}--{V('RBrenMax'+P)} & {V('RCons'+P)} & ({V('cat'+P)})\\\\\n" for P in PS)
    T["S"] = "".join(f"{P} & {V('SyOcxo'+P)} & {V('SySr'+P)} & {V('SaG'+P)} & {V('SaP'+P)} & {V('maxS'+P)}\\\\\n" for P in PS)
    rows = []
    for rho in (2000, 2200, 2670):
        for t, nm in (("BEN", "B89"), ("BN", "B90")):
            rows.append(f"{V('rho'+str(rho))} & {nm} & {V('Rflat'+t+str(rho))} & {V('RA'+t+str(rho))} & {V('RB'+t+str(rho))} & "
                        f"{V('RC'+t+str(rho))} & {V('RD'+t+str(rho))}\\\\\n")
    T["brenR"] = "".join(rows)
    T["brenLam"] = "".join(f"{V('lamS'+l)} & {V('aFlat'+l)} & {V('aA'+l)} & {V('aB'+l)}\\\\\n" for l in ("300", "1000", "3000", "10000", "50000"))
    T["subcmR"] = "".join(f"{V('rL'+l)} & {V('rPlus'+l)} & {V('rEnv'+l)}\\\\\n" for l in ("50", "100", "200", "1000"))
    T["addon"] = "".join(f"{P} & {V('Ginf'+P)} & {V('dyKone'+P)} & {V('kcNeed'+P)}\\\\\n" for P in PS)
    return T


def main(modules_dir, art):
    st = Store(modules_dir, art)
    gen = os.path.join(art, "generated")
    os.makedirs(gen, exist_ok=True)
    ids = [c["id"] for c in CLAIMS]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        raise SystemExit(f"duplicate claim ids: {sorted(dup)}")
    vals = {}
    for c in CLAIMS:
        x = evaluate(c, st)
        if isinstance(x, float) and not math.isfinite(x):
            raise SystemExit(f"{c['id']}: non-finite value")
        en = fmt(x, c["fmt"])
        vals[c["id"]] = (x, en, hu(en) if c["fmt"][0] != "str" else en)
    for lang, idx in (("en", 1), ("hu", 2)):
        with open(os.path.join(gen, f"values_{lang}.tex"), "w") as f:
            f.write("% generated by src/make_values.py from the module archives; do not edit\n")
            for c in CLAIMS:
                s = vals[c["id"]][idx]
                body = s if c["fmt"][0] == "str" else "\\ensuremath{" + s + "}"
                f.write(f"\\expandafter\\def\\csname val@{c['id']}\\endcsname{{{body}}}\n")
    for name, body in tables().items():
        for lang in ("en", "hu"):
            with open(os.path.join(gen, f"tab_{name}.tex"), "w") as f:
                f.write("% generated by src/make_values.py; cells are value macros\n" + body)
    # where each claim is used
    used = {}
    for lang in ("en", "hu"):
        p = os.path.join(art, "tex", f"article_{lang}.tex")
        if not os.path.exists(p):
            continue
        sec = "front"
        for line in open(p, encoding="utf-8"):
            m = re.match(r"\\(section|subsection|appendixsection)\*?\{(.*?)\}", line.strip())
            m2 = re.search(r"\\label\{(sec|app):([^}]*)\}", line)
            if m2:
                sec = m2.group(2)
            for k in re.findall(r"\\V\{([^}]+)\}", line):
                used.setdefault(k, {}).setdefault(lang, set()).add(sec)
            for t in re.findall(r"\\tabinput\s+(?:\.\./)?generated/tab_(\w+)\.tex", line):
                for k in re.findall(r"\\V\{([^}]+)\}", tables()[t]):
                    used.setdefault(k, {}).setdefault(lang, set()).add(sec)
    rows = []
    for c in CLAIMS:
        x, en, hu_ = vals[c["id"]]
        srcs = []
        for s in c["src"]:
            mod = s[0]
            loc = "article/" + s[1] if mod == "article" else f"{MODULES[mod][0]}::{MODULES[mod][1]}{s[1]}"
            srcs.append(f"{loc} [{sel_str(s)}]")
        u = used.get(c["id"], {})
        rows.append({
            "id": c["id"], "claim": c["desc"], "value_raw": repr(x), "printed_en": plain(en), "printed_hu": plain(hu_),
            "unit": c["unit"], "source": " + ".join(srcs), "formula": c["expr"],
            "format": ":".join(str(t) for t in c["fmt"]),
            "sections_en": ";".join(sorted(u.get("en", []))), "sections_hu": ";".join(sorted(u.get("hu", []))),
        })
    with open(os.path.join(art, "CLAIMS_SOURCES.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    with open(os.path.join(art, "CLAIMS_SOURCES.md"), "w", encoding="utf-8") as f:
        f.write("# Claim-source table / Állítás–forrás táblázat\n\n"
                "Generated by `src/make_values.py`; checked by `src/check_claims.py`. Every number printed in the article "
                "is a value macro `\\V{id}` whose row below names the archive, file and key (or CSV row, or text pattern) "
                "it is read from and the formula applied. Sections are the article section labels where the value appears. "
                "/ Generálta a `src/make_values.py`, ellenőrzi a `src/check_claims.py`. A cikk minden kiírt száma egy "
                "`\\V{id}` értékmakró; a sora megadja a forrásarchívumot, a fájlt, a kulcsot és a képletet.\n\n"
                "| id | claim | EN | HU | unit | source (archive::file [key]) | formula | sections |\n|---|---|---|---|---|---|---|---|\n")
        for r in rows:
            src = r["source"].replace("|", "\\|")
            fo = r["formula"].replace("|", "\\|")
            f.write(f"| `{r['id']}` | {r['claim'].replace('|', '/')} | {r['printed_en']} | {r['printed_hu']} | {r['unit']} | {src} | `{fo}` | {r['sections_en']} |\n")
    print(f"{len(CLAIMS)} claims written")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
